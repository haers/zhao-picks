// 系统Chrome独立配置，只访问构建网站，结束后关闭浏览器及本机服务。
import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFile, mkdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const site = path.join(root, 'work/site');
const output = path.join(root, 'work/qa-site');
await mkdir(output, { recursive: true });
const report = { gates: [], consoleErrors: [], pageErrors: [], screenshots: [] };
const server = createServer(async (request, response) => {
  try {
    const pathname = new URL(request.url, 'http://127.0.0.1').pathname;
    if (!pathname.startsWith('/zhao-picks/')) { response.writeHead(404); response.end(); return; }
    let target = path.resolve(site, decodeURIComponent(pathname.slice('/zhao-picks/'.length)));
    if (target !== site && !target.startsWith(site + path.sep)) throw new Error('outside root');
    if ((await stat(target)).isDirectory()) target = path.join(target, 'index.html');
    const data = await readFile(target);
    const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'application/javascript', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.woff2': 'font/woff2' };
    response.writeHead(200, { 'Content-Type': types[path.extname(target)] || 'application/octet-stream' });
    response.end(data);
  } catch { response.writeHead(404); response.end('not found'); }
});
let browser;
try {
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(18431, '127.0.0.1', resolve); });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  page.on('pageerror', error => report.pageErrors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') report.consoleErrors.push(message.text()); });
  const home = 'http://127.0.0.1:18431/zhao-picks/';
  await page.goto(home, { waitUntil: 'networkidle', timeout: 20000 });
  await page.locator('main h1').waitFor();
  assert.match(await page.locator('main').innerText(), /我的开源精选/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  // 验证共享主题实际渲染结果及站点图标接线，避免只改了源码却仍显示旧颜色或无图标。
  const purple = 'rgb(114, 83, 237)';
  const buttonColor = await page.locator('main a.btn-purple').evaluate(link => getComputedStyle(link).backgroundColor);
  assert.equal(buttonColor, 'rgb(87, 57, 206)');
  const linkColor = await page.locator('#site-nav a[href="/zhao-picks/projects/"]').evaluate(link => getComputedStyle(link).color);
  assert.equal(await page.locator('main table').count(), 0);
  assert.equal(await page.locator('main a.btn-purple').evaluate(link => getComputedStyle(link).color), 'rgb(255, 255, 255)');
  const navColor = await page.locator('.nav-list-link.active').first().evaluate(link => getComputedStyle(link).color);
  assert.equal(linkColor, purple);
  assert.equal(navColor, purple);
  assert.equal(await page.locator('meta[name="theme-color"]').getAttribute('content'), '#7253ed');
  const favicon = page.locator('link[rel="icon"]');
  assert.equal(await favicon.getAttribute('type'), 'image/svg+xml');
  const faviconUrl = new URL(await favicon.getAttribute('href'), home).href;
  assert.match(faviconUrl, /favicon\.svg\?v=purple-book-1$/);
  const faviconResponse = await context.request.get(faviconUrl);
  assert.equal(faviconResponse.status(), 200);
  assert.match(await faviconResponse.text(), /Zhao Picks 开源精选/);
  const decodedIcon = await page.evaluate(async src => {
    const image = new Image();
    image.src = src;
    await image.decode();
    return { width: image.naturalWidth, height: image.naturalHeight };
  }, faviconUrl);
  assert.ok(decodedIcon.width > 0 && decodedIcon.height > 0);
  report.theme = { linkColor, navColor, faviconUrl, decodedIcon };
  report.gates.push('G1 原生紫色、SVG favicon资源/解码、theme-color通过');
  await page.screenshot({ path: path.join(output, 'desktop-home.png') });
  report.screenshots.push('desktop-home.png');
  await page.getByRole('link', { name: '浏览项目', exact: true }).click();
  await page.waitForURL('**/projects/');
  assert.equal(await page.locator('main .label').count(), JSON.parse(await readFile(path.join(root, 'work/site-input.json'), 'utf8')).projects);
  await page.screenshot({ path: path.join(output, 'desktop-directory.png') });
  report.screenshots.push('desktop-directory.png');
  await page.locator('main a[href="/zhao-picks/reviews/stretchly/"]').click();
  await page.waitForURL('**/reviews/stretchly/');
  assert.match(await page.locator('main h1').innerText(), /Stretchly/);
  await page.screenshot({ path: path.join(output, 'desktop-detail.png') });
  report.screenshots.push('desktop-detail.png');
  assert.equal(await page.locator('.page-context').count(), 0);
  assert.equal(await page.locator('.breadcrumb-nav').count(), 1);
  assert.equal(await page.locator('main .label').innerText(), '初步试用');
  await page.locator('.breadcrumb-nav a').filter({ hasText: '项目目录' }).click();
  await page.waitForURL('**/projects/');
  await page.locator('.site-title').click();
  await page.waitForURL(home);
  report.gates.push('G2 首页按钮→目录→详情→原生面包屑→目录→页头首页通过');
  const search = page.getByRole('searchbox', { name: '搜索项目、用途或关键词' });
  await search.focus();
  assert.equal(await search.evaluate(input => getComputedStyle(input).outlineColor), purple);
  await search.fill('生词');
  const results = page.locator('#picks-search-results');
  const vocabularyResult = results.getByRole('link', { name: /AI Vocabulary Builder/ });
  await vocabularyResult.hover();
  assert.equal(await vocabularyResult.evaluate(link => getComputedStyle(link).color), purple);
  report.theme.searchFocusColor = await search.evaluate(input => getComputedStyle(input).outlineColor);
  report.theme.searchHoverBackground = await vocabularyResult.evaluate(link => getComputedStyle(link).backgroundColor);
  await page.screenshot({ path: path.join(output, 'desktop-search-purple.png') });
  report.screenshots.push('desktop-search-purple.png');
  await vocabularyResult.click();
  await page.waitForURL('**/reviews/ai-vocabulary-builder/');
  await search.fill('Stretchly');
  await results.getByRole('link', { name: /Stretchly/ }).waitFor();
  await search.fill('不存在的项目测试关键词');
  await results.getByRole('status').filter({ hasText: '没有找到' }).waitFor();
  await search.press('Escape');
  assert.equal(await results.isVisible(), false);
  report.gates.push('G3 中文/英文搜索、结果跳转、空结果与Escape关闭通过');
  await page.goto(home + '404.html', { waitUntil: 'networkidle' });
  await page.locator('main a').filter({ hasText: '返回精选首页' }).click();
  await page.waitForURL(home);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(await search.isVisible(), true);
  assert.equal(await page.locator('main table').count(), 0);
  await page.screenshot({ path: path.join(output, 'mobile-home.png') });
  report.screenshots.push('mobile-home.png');
  const toggle = page.locator('#menu-button');
  await toggle.click();
  const nav = page.locator('#site-nav');
  await nav.getByRole('link', { name: '项目目录', exact: true }).click();
  await page.waitForURL('**/projects/');
  assert.equal(await page.locator('main .picks-directory').evaluate(table => getComputedStyle(table).display), 'block');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(output, 'mobile-directory.png') });
  report.screenshots.push('mobile-directory.png');
  await page.locator('main a[href="/zhao-picks/reviews/bibigpt-v1/"]').click();
  await page.waitForURL('**/reviews/bibigpt-v1/');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(output, 'mobile-detail.png') });
  report.screenshots.push('mobile-detail.png');
  report.gates.push('G3 404返回、390手机导航/详情、无横向溢出通过');
  assert.deepEqual(report.pageErrors, []);
  assert.deepEqual(report.consoleErrors, []);
  report.status = 'passed';
  report.browser = browser.version();
  console.log(JSON.stringify(report));
} catch (error) {
  report.status = 'failed'; report.error = String(error); console.error(error); process.exitCode = 1;
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  await writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2));
}
